#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0

// Bind a build artifact into the firmware test suite as a byte array.
//
// The suites that consume these headers admit RELEASE output through the real
// device parsers, so the bytes have to be the packaged SDK's actual output
// rather than something a test re-encodes. The generated header is committed
// and CI regenerates it and compares, which is what makes a silent change in
// the compiler, the post-link gate, or the package builder visible.
//
//   bytes-to-header.mjs <input> <output.h> <symbol> <spdx> <copyright> <license>

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [inputArg, outputArg, symbolArg, spdxArg, copyrightArg, licenseArg] = process.argv.slice(2);
if (!inputArg || !outputArg || !symbolArg || !spdxArg || !copyrightArg || !licenseArg ||
    !/^[A-Za-z_][A-Za-z0-9_]*$/.test(symbolArg) || !/^[A-Za-z0-9.-]+$/.test(spdxArg)) {
  console.error(
    "usage: bytes-to-header.mjs <input> <output.h> <symbol> <spdx> <copyright> <license>",
  );
  process.exit(2);
}

// The copyright and license strings are emitted into // comment lines. Reject
// anything that could break out of a comment or the line it sits on: only
// single-line printable ASCII, and never a comment-closing sequence. The
// symbol and SPDX are already constrained to identifier/token characters
// above, and the bytes below only ever become 0xNN literals, so a crafted file
// name or byte content cannot inject into the generated header either.
function requireCommentSafe(value, label) {
  if (!/^[\x20-\x7e]+$/.test(value) || value.includes("*/") || value.includes("/*")) {
    console.error(`error: ${label} must be single-line printable ASCII with no comment markers`);
    process.exit(2);
  }
  return value;
}
requireCommentSafe(copyrightArg, "copyright");
requireCommentSafe(licenseArg, "license");

const bytes = readFileSync(resolve(inputArg));
const digest = createHash("sha256").update(bytes).digest("hex");
const rows = [];
for (let offset = 0; offset < bytes.length; offset += 16) {
  const values = Array.from(bytes.subarray(offset, offset + 16),
                            (value) => `0x${value.toString(16).padStart(2, "0")}`);
  rows.push(`    ${values.join(", ")},`);
}
writeFileSync(resolve(outputArg), [
  "#pragma once",
  "",
  "#include <cstddef>",
  "#include <cstdint>",
  "",
  `// SPDX-License-Identifier: ${spdxArg}`,
  `// ${copyrightArg}`,
  `// Full permission notice: ${licenseArg}.`,
  "// Generated by the release-pinned RGBX v2 SDK consumer build.",
  `// SHA-256: ${digest}.`,
  `inline constexpr uint8_t ${symbolArg}[] = {`,
  ...rows,
  "};",
  "",
].join("\n"));
